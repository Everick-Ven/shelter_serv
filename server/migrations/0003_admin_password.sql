-- ---------------------------------------------------------------------------
-- 0003: парольный вход администратора.
--
-- Панель /manage доступна по логину+паролю независимо от OAuth: OAuth может
-- быть не настроен, а оператору нужен вход «здесь и сейчас». Храним только
-- scrypt-хэш с солью; plaintext не появляется ни в БД, ни в логах.
-- ---------------------------------------------------------------------------

ALTER TABLE users
    ADD COLUMN IF NOT EXISTS password_hash TEXT;

-- Пароль есть только у живых аккаунтов; после DELETE /me (анонимизация)
-- хэш стирается вместе с остальными персональными данными.
COMMENT ON COLUMN users.password_hash IS
    'scrypt-хэш пароля входа в панель (/manage); NULL = парольный вход не настроен';
